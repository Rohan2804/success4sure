"""Merge js/data/qbank/*.json into js/data/qbank.js (loaded after questions.js; full banks replace the samples).
Run:  python3 -I tools/build_qbank.py   (from the project root)
"""
import json, glob, os, re, random, hashlib

# Options that point at other options must keep their order.
POSITIONAL = re.compile(r'\b(all|none|both|neither) of the (above|these)\b|\b(both|either|neither)\b.*\b(and|or|nor)\b|\b[A-D] (and|&|or) [A-D]\b|\(?[a-d]\)? and \(?[a-d]\)?', re.I)

# Data sufficiency / syllogism / assumption answer sets have a conventional fixed order.
CONVENTIONAL = re.compile(r'\b(statements?|conclusions?|assumptions?|courses? of action)\b|\bonly (I|II|III)\b|\b(I|II) (and|or) (II|III)\b', re.I)

# Options that are just part labels, e.g. error spotting "(A)"…"(D)".
LABEL = re.compile(r'^\(?[A-Ea-e1-5]\)?$')

def reshuffle(exam, q):
    """Deterministically shuffle option order so answer letters vary between exams."""
    ch, text, opts, ans, expl = q
    if any(POSITIONAL.search(o) or CONVENTIONAL.search(o) or LABEL.match(o.strip()) for o in opts):
        return q
    rnd = random.Random(int(hashlib.sha1((exam + '|' + text).encode()).hexdigest(), 16))
    order = list(range(4)); rnd.shuffle(order)
    return [ch, text, [opts[i] for i in order], order.index(ans), expl]

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
merged = {}
for path in sorted(glob.glob(os.path.join(root, 'js', 'data', 'qbank', '*.json'))):
    for exam, qs in json.load(open(path, encoding='utf-8')).items():
        merged[exam] = [reshuffle(exam, q) for q in qs]
out = os.path.join(root, 'js', 'data', 'qbank.js')
with open(out, 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/build_qbank.py from js/data/qbank/*.json — edit the JSON, then re-run the script.\n')
    f.write('Object.assign(window.QUESTIONS, ')
    json.dump(merged, f, ensure_ascii=False, separators=(',', ':'))
    f.write(');\n')
print(f'{len(merged)} exams, {sum(len(v) for v in merged.values())} questions -> {os.path.relpath(out, root)}')
